from dataclasses import dataclass
from pathlib import Path

from hyraxdotplot.models import Contig


@dataclass
class Assembly:
    """Represent a genome assembly containing ordered contigs"""

    contigs: dict[str, Contig]

    @classmethod
    def from_fai(cls, path: str | Path) -> "Assembly":
        """Construct an assembly from a fasta index file
        (.fai), as generated by samtools"""

        lengths: dict[str, int] = {}
        with Path(path).open(encoding="utf-8") as handle:
            for line_number, line in enumerate(handle, start=1):
                fields = line.rstrip("\n").split("\t")

                if len(fields) < 2:
                    raise ValueError(f"Invalid FAI record at line {line_number}")

                name = fields[0]
                length = int(fields[1])

                if name in lengths:
                    raise ValueError(f"Duplicate contig name: {name}")

                lengths[name] = length

        if not lengths:
            raise ValueError("FAI file is empty!")

        sorted_contigs = sorted(lengths.items(), key=lambda item: item[1], reverse=True)
        contigs: dict[str, Contig] = {}
        offset = 0
        for name, length in sorted_contigs:
            contig = Contig(name=name, length=length, offset=offset)
            contigs[name] = contig
            offset = contig.end
        return cls(contigs=contigs)

    @property
    def total_length(self) -> int:
        """Return the combined length of all contigs"""
        return sum(contig.length for contig in self.contigs.values())

    @property
    def contig_count(self) -> int:
        """Return the number of contigs"""
        return len(self.contigs)

    def to_global(self, contig_name: str, position: int) -> int:
        """Convert a local boundary coordinate to an assembly coordinate"""
        contig = self.contigs[contig_name]
        if not 0 <= position <= contig.length:
            raise ValueError("Position is outside contig boundaries")
        return contig.offset + position
